import { readFileSync, readdirSync } from 'node:fs';
import { extname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { extractSampleFiles } from 'generator-jhipster/ci';
import BaseCoreGenerator from 'generator-jhipster/generators/base-core';

import { findSamples } from '../describe-samples/support/describe-samples.mjs';

const GENERATOR_JDL = 'jdl';

const packageRoot = fileURLToPath(new URL('../../', import.meta.url));
const packageJson = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf-8'));

/**
 * Generates a sample by its name alone, like generate-sample of generator-jhipster: the sample of describe-samples, its
 * files copied to the project, generated by its command.
 */
export default class extends BaseCoreGenerator {
  /** @type {string} */
  sampleName;
  /** @type {boolean | undefined} */
  all;
  /** @type {import('generator-jhipster/ci').SampleDescription | undefined} */
  sample;
  /** @type {import('generator-jhipster/ci').SampleFile[]} */
  sampleFiles = [];
  /** @type {string[]} The jdl files of the project, the jdl generator generating them. */
  jdlFiles = [];

  get [BaseCoreGenerator.WRITING]() {
    return this.asAnyTaskGroup({
      async copySample() {
        if (this.all || extname(this.sampleName) === '.jdl') {
          this.jdlFiles = this.all ? readdirSync(this.templatePath('samples')).filter(file => extname(file) === '.jdl') : [this.sampleName];
          for (const file of this.jdlFiles) {
            this.copyTemplate(`samples/${file}`, file, { noGlob: true });
          }
        } else {
          const [sample] = findSamples({ sampleName: this.sampleName });
          this.sample = sample;
          this.sampleFiles = extractSampleFiles(sample, { root: packageRoot });
          for (const file of this.sampleFiles) {
            const destination = this.destinationPath(file.destination);
            if ('source' in file) {
              this.fs.copy(file.source, destination);
            } else {
              this.fs.write(destination, file.contents);
            }
          }
          this.jdlFiles = this.sampleFiles.map(file => file.destination).filter(destination => extname(destination) === '.jdl');
        }
      },
    });
  }

  get [BaseCoreGenerator.END]() {
    return this.asAnyTaskGroup({
      async generateSample() {
        const generatorOptions = {
          projectVersion: `${packageJson.version}-git`,
          skipJhipsterDependencies: true,
        };
        const { sample, jdlFiles } = this;
        if (!sample) {
          await this.composeWithJHipster(GENERATOR_JDL, {
            generatorArgs: jdlFiles,
            generatorOptions: {
              ...generatorOptions,
              ...(this.all ? { workspaces: true, monorepository: true } : {}),
            },
          });
          return;
        }

        await this.composeWithJHipster(jdlFiles.length > 0 ? GENERATOR_JDL : sample.defaultCommand, {
          generatorArgs: jdlFiles,
          generatorOptions: {
            ...generatorOptions,
            ...(sample.environment ? { defaultEnvironment: sample.environment } : {}),
            ...sample.generatorOptions,
          },
        });
      },
      async info() {
        await this.composeWithJHipster('info');
      },
    });
  }
}
