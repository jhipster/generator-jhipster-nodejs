import { fileURLToPath } from 'node:url';

import { convertToGitHubMatrix, describeGithubSamples, getGithubSamplesGroup, getGithubSamplesGroups } from 'generator-jhipster/ci';

export { formatSample, formatSamplesList } from 'generator-jhipster/ci';

/** @typedef {import('generator-jhipster/ci').SampleDescription} SampleDescription */
/** @typedef {SampleDescription['jdls'][string]} SampleJDL */

/** The folder of the samples groups (`<group>.js`) and of their samples (`samples/`). */
export const samplesGroupFolder = fileURLToPath(new URL('../../generate-sample/templates/', import.meta.url));

/** Every described workflow: the samples groups of the blueprint, the `<group>.js` modules. */
export const WORKFLOWS = (await getGithubSamplesGroups(samplesGroupFolder, true))
  .filter(file => file.endsWith('.js'))
  .map(file => file.replace(/\.js$/, ''));

/**
 * The CI samples of the blueprint, described like the ones of generator-jhipster (its `.blueprint/describe-samples`):
 * the samples groups are the workflows of the CI, a sample is generated by its name alone (`generate-sample <name>`).
 */
const descriptions = await describeGithubSamples({
  samplesGroupFolder,
  groups: WORKFLOWS,
  root: fileURLToPath(new URL('../../../', import.meta.url)),
});

/**
 * Describe the CI samples: what each job generates and the environment it runs on.
 * @param {{ workflow?: string }} [options]
 * @returns {SampleDescription[]}
 */
export const describeSamples = ({ workflow } = {}) =>
  workflow ? descriptions.filter(sample => sample.workflow === workflow) : descriptions;

/**
 * The samples of a workflow, every workflow when omitted, or the sample of a name or a job name.
 * @param {{ sampleName?: string; workflow?: string }} [options]
 * @returns {SampleDescription[]}
 */
export const findSamples = ({ sampleName, workflow } = {}) => {
  const samples = describeSamples({ workflow });
  if (!sampleName) return samples;
  const found = samples.filter(sample => sample.name === sampleName || sample.jobName === sampleName);
  if (found.length === 0) {
    // The names, so the caller, an AI agent too, can correct the name by itself.
    throw new Error(`Sample ${sampleName} not found, expected one of ${samples.map(sample => sample.name).join(', ')}`);
  }
  return found;
};

/**
 * A samples group, a workflow, with the names of its samples; an object, to grow with more data.
 * @typedef {{ samples: string[] }} SampleGroupSummary
 */

/**
 * A sample, generated by its name only (`generate-sample <name>`): the command generating it, the files and the jdl
 * generate-sample copies to the project.
 * @typedef {Pick<SampleDescription, 'workflow' | 'jobName' | 'disabled' | 'defaultCommand' | 'files' | 'jdls'>} SampleSummary
 */

/**
 * The samples of a samples group by name; an object, to grow with more data.
 * @typedef {{ samples: Record<string, SampleSummary> }} SampleGroupDescription
 */

/**
 * @param {SampleDescription} sample
 * @returns {SampleSummary}
 */
const summaryOf = ({ workflow, jobName, disabled, defaultCommand, files, jdls }) => ({
  workflow,
  jobName,
  disabled,
  defaultCommand,
  files,
  jdls,
});

/**
 * The samples of a samples group, a workflow, by name.
 * @param {string} group
 * @returns {SampleGroupDescription}
 */
export const describeSampleGroup = group => {
  if (!WORKFLOWS.includes(group)) {
    throw new Error(`Samples group ${group} not found, expected one of ${WORKFLOWS.join(', ')}`);
  }
  return { samples: Object.fromEntries(describeSamples({ workflow: group }).map(sample => [sample.name, summaryOf(sample)])) };
};

/**
 * The samples groups, the workflows, by name, with the names of their samples.
 * @returns {Record<string, SampleGroupSummary>}
 */
export const describeSampleGroups = () =>
  Object.fromEntries(
    WORKFLOWS.map(group => [group, { samples: descriptions.filter(sample => sample.workflow === group).map(sample => sample.name) }]),
  );

/**
 * A sample, by its name or its job name, the names being unique across the samples groups.
 * @param {string} name
 * @returns {SampleSummary}
 */
export const describeSample = name => summaryOf(findSamples({ sampleName: name })[0]);

/**
 * The samples the CI runs for changed files, by samples group (workflow), like the describeChangedSamples of
 * generator-jhipster: the CI of the blueprint runs every sample of its matrix on any pull request, whatever the files, so
 * it is the matrix of each workflow (github-build-matrix), the groups without samples left out.
 * @param {string[]} _files the changed files, relative to the repository root
 * @returns {Promise<Record<string, string[]>>}
 */
export const describeChangedSamples = async _files => {
  const selected = {};
  for (const group of WORKFLOWS) {
    const { samples } = await getGithubSamplesGroup(samplesGroupFolder, group);
    // The sample of a job of the matrix is the sample name.
    const { include = [] } = convertToGitHubMatrix(samples);
    const names = include.map(job => job.sample);
    if (names.length > 0) {
      selected[group] = names;
    }
  }
  return selected;
};
