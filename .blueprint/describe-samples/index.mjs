import { fileURLToPath } from 'node:url';

import { describeGithubSamples, getGithubSamplesGroups } from 'generator-jhipster/ci';

/**
 * The CI samples of the blueprint, described like the ones of generator-jhipster (its `.blueprint/describe-samples`):
 * the samples groups are the workflows of the CI, a sample is generated by its name alone (`generate-sample <name>`).
 */

/** The folder of the samples groups (`<group>.json`) and of their samples (`samples/`). */
export const samplesGroupFolder = fileURLToPath(new URL('../generate-sample/templates/', import.meta.url));

/** The root of the blueprint, the files of the descriptions are relative to. */
export const root = fileURLToPath(new URL('../../', import.meta.url));

/** The samples groups, the `<group>.json` files: the samples folder is not a group, its samples belong to the groups. */
export const groups = (await getGithubSamplesGroups(samplesGroupFolder, true))
  .filter(file => file.endsWith('.json'))
  .map(file => file.replace(/\.json$/, ''));

/** Every sample, described once: the contract below is synchronous, like the one of generator-jhipster. */
const descriptions = await describeGithubSamples({ samplesGroupFolder, groups, root });

/**
 * A sample, generated by its name only: the command generating it, the files and the jdl generate-sample copies to the
 * project, and the options it generates them with (a jdl template of the samples folder shared by several samples).
 * @typedef {Pick<import('generator-jhipster/ci').SampleDescription, 'workflow' | 'jobName' | 'disabled' | 'defaultCommand' | 'files' | 'jdls' | 'generatorOptions'>} SampleSummary
 */

/** @returns {SampleSummary} */
const summaryOf = ({ workflow, jobName, disabled, defaultCommand, files, jdls, generatorOptions }) => ({
  workflow,
  jobName,
  disabled,
  defaultCommand,
  files,
  jdls,
  generatorOptions,
});

/**
 * The samples groups, the workflows, by name, with the names of their samples.
 * @returns {Record<string, { samples: string[] }>}
 */
export const describeSampleGroups = () =>
  Object.fromEntries(
    [...new Set(descriptions.map(sample => sample.workflow))].map(group => [
      group,
      { samples: descriptions.filter(sample => sample.workflow === group).map(sample => sample.name) },
    ]),
  );

/**
 * The samples of a samples group, a workflow, by name.
 * @param {string} group
 * @returns {{ samples: Record<string, SampleSummary> }}
 */
export const describeSampleGroup = group => {
  const groups = describeSampleGroups();
  if (!groups[group]) {
    throw new Error(`Samples group ${group} not found, expected one of ${Object.keys(groups).join(', ')}`);
  }
  return {
    samples: Object.fromEntries(descriptions.filter(sample => sample.workflow === group).map(sample => [sample.name, summaryOf(sample)])),
  };
};

/**
 * A sample, by its name or its job name, the names being unique across the samples groups.
 * @param {string} name
 * @returns {SampleSummary & { name: string }}
 */
export const describeSample = name => {
  const sample = descriptions.find(candidate => candidate.name === name || candidate.jobName === name);
  if (!sample) {
    // The names, so the caller, an AI agent too, can correct the name by itself.
    throw new Error(`Sample ${name} not found, expected one of ${descriptions.map(candidate => candidate.name).join(', ')}`);
  }
  return { name: sample.name, ...summaryOf(sample) };
};
